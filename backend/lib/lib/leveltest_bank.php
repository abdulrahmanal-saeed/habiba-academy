/** نفس منطقك القديم لقراءة/استماع */
function lt_level_from_score(int $score, int $max): string {
  $pct = $max > 0 ? ($score / $max) : 0.0;
  if ($pct < 0.15) return 'A1'; // BEFORE: A2 was minimum — now A1 for truly zero-level
  if ($pct < 0.40) return 'A2';
  if ($pct < 0.55) return 'B1';
  if ($pct < 0.70) return 'B2';
  if ($pct < 0.85) return 'C1';
  return 'C2';
}


/** Final level من إجمالي 95 */
function lt_level_from_total95(int $score95): string {
  $pct = $score95 / 95.0;
  if ($pct < 0.15) return 'A1'; // BEFORE: A2 was minimum — now A1 for <15%
  if ($pct < 0.40) return 'A2';
  if ($pct < 0.55) return 'B1';
  if ($pct < 0.70) return 'B2';
  if ($pct < 0.85) return 'C1';
  return 'C2';
}


