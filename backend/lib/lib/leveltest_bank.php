/** level من rubric score 0-20 */
function lt_level_from_rubric20(int $score): string {
  if ($score <= 1)  return 'A1'; // BEFORE: A2 was minimum
  if ($score <= 6)  return 'A2';
  if ($score <= 10) return 'B1';
  if ($score <= 14) return 'B2';
  if ($score <= 17) return 'C1';
  return 'C2';
}


