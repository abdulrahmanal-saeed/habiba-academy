function lt_writing_task2_for_level(string $level): string {
  switch ($level) {
    case 'B1':
      return 'اكتب 120–150 كلمة عن: "هل التكنولوجيا تسهل حياتنا أم تجعلها أكثر تعقيدًا؟ ولماذا؟"';
    case 'B2':
      return 'اكتب 150–180 كلمة تناقش: "تأثير وسائل التواصل الاجتماعي على العلاقات الاجتماعية." قدم رأيك مع أمثلة.';
    case 'C1':
      return 'اكتب مقالًا تحليليًا (180–220 كلمة): "هل يجب أن تكون حرية التعبير مطلقة في جميع المجتمعات؟" ناقش وجهتي نظر قبل أن تقدم رأيك.';
    case 'C2':
      return 'اكتب مقالًا جدليًا منظمًا (220–250 كلمة): "إلى أي مدى يمكن تحقيق التوازن بين الحرية الفردية والمسؤولية المجتمعية؟" حلل الفكرة بعمق وقدم حججًا مضادة ورد عليها.';
    case 'A1':
      return 'اكتب 3 جمل قصيرة عن نفسك: اسمك، بلدك، وشيء تحبه.';
